"""Кредиты: перевод себестоимости в цену и обратно. Без float в деньгах.

Курс и маржа — решение владельца (`docs/SAAS-PIVOT.md` §5.1): 1 кредит = $1,
маржа ×3. Оба параметра вынесены в настройки, потому что менять их придётся
без правки кода, но по умолчанию стоят решённые значения.

**Почему целые микрокредиты.** Самая дешёвая операция конвейера — одна
картинка за $0.0035, то есть 0.0105 кредита. Кредит обязан быть дробным, а
дробное в деньгах — это либо `Decimal`, либо целое в мелкой единице. Взято
второе: 1 микрокредит = 10⁻⁶ кредита, хранение — `bigint`. Сложение баланса
тогда точное по построению, а не «почти точное».

**Округление несимметрично, и это намеренно.** Цена округляется ВВЕРХ,
баланс — ВНИЗ. Иначе на дроблении шагов возникает бесплатная работа:
двадцать четыре кадра по 0.0105 кредита, округлённые к ближайшему, дают
ноль. Правило одно: клиент никогда не видит баланс больше фактического и
никогда не платит меньше себестоимости с маржой.

Смотри также `app/services/quote.py` — там оценка в долларах, здесь только
перевод в кредиты.
"""

from __future__ import annotations

from decimal import ROUND_CEILING, ROUND_FLOOR, ROUND_HALF_UP, Decimal

from app.settings import settings

#: Микрокредитов в кредите. Единица хранения баланса и проводок.
MICRO: int = 1_000_000

_USD = Decimal(1)

#: Дробность учёта расходов — как в `media_ledger.compute_cost`.
_CENT_FRACTION = Decimal("0.000001")


def margin() -> Decimal:
    """Наценка на себестоимость. По умолчанию ×3 (§5.1)."""
    return Decimal(str(getattr(settings, "credit_margin", 3.0)))


def usd_per_credit() -> Decimal:
    """Сколько долларов себестоимости в одном кредите. По умолчанию $1."""
    rate = Decimal(str(getattr(settings, "credit_usd_rate", 1.0)))
    return rate if rate > 0 else _USD


def price_micro(cost_usd: float | Decimal, *, with_margin: bool = True) -> int:
    """Себестоимость в долларах → цена в микрокредитах, округление ВВЕРХ.

    ``with_margin=False`` — перевод по курсу без наценки (нужен, чтобы
    показать в отчёте себестоимость в тех же единицах, что и цену).
    """
    # Вход квантуется до дробности учёта: `0.19 * 24` в float — это
    # 4.5600000000000005, и округление ВВЕРХ превратило бы двоичную пыль в
    # лишний микрокредит (13.69 кредита вместо 13.68). Шесть знаков — та же
    # дробность, в какой `media_ledger.compute_cost` пишет фактический
    # расход: смета и списание обязаны считать одинаково.
    usd = Decimal(str(cost_usd)).quantize(_CENT_FRACTION, rounding=ROUND_HALF_UP)
    if usd <= 0:
        return 0
    if with_margin:
        usd *= margin()
    micro = usd / usd_per_credit() * MICRO
    return int(micro.to_integral_value(rounding=ROUND_CEILING))


def micro_to_usd(micro: int, *, with_margin: bool = True) -> Decimal:
    """Микрокредиты → доллары. Обратная ``price_micro`` с точностью до
    округления вверх: годится для отчётов, не для сверки леджера."""
    usd = Decimal(int(micro)) / MICRO * usd_per_credit()
    return usd / margin() if with_margin else usd


def format_credits(micro: int, *, rounding: str = "down") -> str:
    """Микрокредиты → строка для человека.

    ``rounding='down'`` — для баланса (не обещать лишнего),
    ``'up'`` — для цены (не занижать).

    **Знаков столько, сколько несёт смысл.** Два знака хороши для баланса и
    для ролика целиком, но одна картинка стоит 0.0105 кредита: округлив её
    вверх до 0.01, показали бы цену на 90% выше настоящей. Поэтому ниже
    одного кредита показываются четыре знака. Дешёвая операция должна
    выглядеть дешёвой — на этом держится всё поведение продукта, где
    итерация идёт по картинкам, а видео покупается один раз (§6.3).
    """
    value = Decimal(int(micro)) / MICRO
    mode = ROUND_FLOOR if rounding == "down" else ROUND_CEILING
    step = Decimal("0.01") if value >= 1 else Decimal("0.0001")
    shown = value.quantize(step, rounding=mode)
    if shown == 0 and value > 0:
        return "<0.0001"
    return f"{shown:.2f}" if value >= 1 else f"{shown:.4f}".rstrip("0").rstrip(".")


def hold_micro(p90_usd: float | Decimal) -> int:
    """Сколько резервировать под шаг: цена по оценке p90 (§5.4).

    Резервируется верхняя граница, а не медиана: холд, которого не хватило
    на фактический расход, означает либо уход баланса в минус, либо
    остановку шага на середине. Излишек возвращается при списании.
    """
    return price_micro(p90_usd)
