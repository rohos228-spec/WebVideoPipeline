"""Промты, встроенные в код, и их посев в базу.

Некоторые шаги обязаны работать и без библиотеки на диске: на сервере
каталог `prompts/` смонтирован только для чтения и неполон, а шаг разбора
состава (`cast_extract`) появился позже библиотеки — файла для него там нет.

Поэтому текст живёт в коде, а на старте один раз кладётся в базу на
системный уровень. Дальше это обычный промт: виден в редакторе, правится,
переопределяется на уровне арендатора. Повторный посев ничего не трогает —
затирать правку человека встроенным текстом нельзя.
"""

from __future__ import annotations

from typing import Any

from loguru import logger


def builtin_prompts() -> dict[tuple[str, str], str]:
    """(код шага, имя) → текст. Функция, а не константа: импорт ленивый."""
    from app.services.cast_extract import DEFAULT_PROMPT as cast_default

    return {
        ("cast", "default"): cast_default,
        ("hero_style", "default"): HERO_STYLE_DEFAULT,
        ("items", "default"): ITEMS_STYLE_DEFAULT,
    }


#: Стиль референсов предметов. Папка `04b_items/` пуста так же, как
#: `04_hero_style/`; без стиля предмет рисовался «из описания» — в любой
#: манере и с любым фоном, и дальше по конвейеру его не вставить в кадр.
ITEMS_STYLE_DEFAULT = """\
# Стиль референсов предметов

Та же манера, что у персонажей этого ролика: одна техника, одна палитра,
одно освещение.

Лист референса предмета:
- один предмет, целиком, крупно, в центре кадра;
- ровный нейтральный фон без деталей и без рук, которые его держат;
- мягкий рассеянный свет, без цветных бликов и отражений;
- никаких подписей, текста, водяных знаков и рамок — даже если на самом
  предмете по описанию есть надпись, она должна быть читаемой частью
  предмета, а не подписью к картинке.

Внешность — строго по описанию: материал, цвет, состояние (новый, потёртый,
разбитый). Не добавлять деталей, которых в описании нет.
"""


#: Стиль референсов персонажей по умолчанию.
#:
#: Папка `04_hero_style/` в библиотеке пуста — стиля не было нигде, и шесть
#: героев одного ролика выходили в шести манерах. Это не вкус, а ремесло:
#: референс нужен, чтобы дальше рисовать ТОГО ЖЕ персонажа, и для этого он
#: обязан быть единообразным и читаемым. Что именно за манера (мультфильм,
#: фотореализм, комикс) — решает человек, правя этот текст в редакторе.
HERO_STYLE_DEFAULT = """\
# Стиль референсов персонажей

Единая манера для ВСЕХ персонажей ролика: одна техника, одна палитра, одно
освещение. Персонажи одного ролика должны выглядеть как из одного мира.

Лист референса:
- персонаж в полный рост, нейтральная поза, лицо крупно отдельно;
- ровный нейтральный фон без деталей — фон не часть персонажа;
- мягкий рассеянный свет без цветных бликов;
- никаких подписей, текста, водяных знаков, рамок и коллажей.

Внешность — строго по описанию из брифа: возраст, телосложение, одежда,
приметы. Не добавлять аксессуаров и деталей, которых в описании нет.
"""


async def seed_builtin_prompts(session: Any) -> int:
    """Положить встроенные промты в базу, если их там ещё нет. Возвращает число."""
    from app.services import prompt_store
    from app.services.prompt_store import PromptScope

    system = PromptScope()
    seeded = 0
    for (step_code, name), text in builtin_prompts().items():
        if prompt_store.resolve(step_code, name, system) is not None:
            continue
        await prompt_store.save(session, step_code, name, text, scope=system)
        seeded += 1
        logger.info("промт-библиотека: встроенный промт {}/{} посеян в базу", step_code, name)
    return seeded
