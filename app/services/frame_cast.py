"""Кто в кадре получит фотореференс, а кого придётся описать словами.

`image-01` у MiniMax принимает РОВНО ОДНУ character-ссылку («provide a single
front-facing portrait photo» — api-reference/image-generation-i2i). Пайплайн
при этом честно грузит все найденные рефы кадра, а в запрос уходит первый.
На живом прогоне #2 это дало кадр 12: «женщина в сером пальто входит в вагон»
нарисована мужчиной с лицом c01 — второй герой остался без ссылки, и модель
достроила его от первой.

Послать второй файл некуда, поэтому сходство второго героя может держать
только текст. Проверено на живых кадрах 12/13/17, три варианта:

* реф есть, описан только второй герой — второй всё равно выходит с полом и
  лицом первого: фотография перебивает слова;
* рефа нет вовсе — второй герой получается верно, зато **первый** уезжает
  следом за единственным описанием в промте (кадр 13: оба героя стали
  женщинами);
* реф есть и описаны ОБА — у модели остаётся, чем их различать.

Отсюда правило. В кадре один человек — описание не нужно, фотография
справляется и бюджет (1500 символов у MiniMax) тратить не на что. В кадре
двое и больше — коротко описываются **все**, включая того, у кого есть
фотография: без своей строчки он растворяется в описании соседа.

Кому достанется сама фотография — известно заранее: ПЕРВОМУ ``cNN`` в поле
``characters`` кадра, ровно так её берёт
``generate_images._load_refs_for_frame``. Разойдутся правила — промт будет
описывать не того, и брак вернётся.
"""

from __future__ import annotations

import re
from typing import Any

_CHAR_ID = re.compile(r"^c\d{1,3}$")
_SEPARATORS = (";", "+", "/", "|", " ")


def cast_ids_in_order(raw: Any) -> list[str]:
    """``«c01, c02 женщина»`` → ``['c01', 'c02']``, порядок исходный, без дублей."""
    text = str(raw or "").strip()
    if not text:
        return []
    for ch in _SEPARATORS:
        text = text.replace(ch, ",")
    out: list[str] = []
    for tok in text.split(","):
        t = tok.strip().lower().rstrip(":;,.)]}»\"'")
        if _CHAR_ID.match(t) and t not in out:
            out.append(t)
    return out


def reference_character(raw: Any) -> str:
    """Кому приедет фотография. Пусто — фотореференса у кадра не будет."""
    ids = cast_ids_in_order(raw)
    return ids[0] if ids else ""


def characters_needing_description(raw: Any) -> list[str]:
    """Кого промт обязан описать словами.

    Один человек в кадре — никого: фотография справляется сама. Двое и
    больше — всех: фотография достанется одному, и без описания второй
    получается его лицом, а без описания первого он уезжает за описанием
    второго (см. докстринг модуля — проверено на кадрах 12/13/17).
    """
    ids = cast_ids_in_order(raw)
    return ids if len(ids) > 1 else []
