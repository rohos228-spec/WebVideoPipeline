"""Персонажи и предметы, выведенные из плана и закадрового текста.

**Зачем.** Шаг «Герои и предметы» ждёт готовых описаний. У владельца их
заполняет лист «Персонажи» в книге проекта; при учётных записях книги нет, и
заполнить их некому — шаг молча пропускался, а конвейер вставал. Живой прогон
2026-08-25 остановился ровно здесь: план был написан и в нём прямым текстом
стояло «четверо помятых жизнью агентов», но до `hero_descriptions` это не
доезжало.

**Почему разбор текста, а не структурированный вывод.** Схему enforce'ят
только релеи из `GPT_STRUCTURED_RELAYS`; остальные (и MiniMax, на котором это
писалось) принимают `response_format` молча и игнорируют. Единственная
опора — жёсткий формат в самом промте плюс разбор на клиенте. Поэтому просим
плоский список и разбираем построчно, а не парсим JSON, которого может не
быть.

**Результат — предложение, а не приговор.** Списки кладутся в проект, где их
видно в редакторе: пользователь правит формулировки или убирает лишнее, и
только потом жмёт генерацию референсов. Иначе модель молча определяла бы, как
выглядит ролик.
"""

from __future__ import annotations

import re

from loguru import logger

#: Заголовки разделов в ответе. Регистр и род не фиксируем: модель склоняет.
_HEAD_PEOPLE = re.compile(r"^\s*#*\s*(персонаж|герои|герой|действующие)", re.IGNORECASE)
_HEAD_THINGS = re.compile(r"^\s*#*\s*(предмет|объект|реквизит)", re.IGNORECASE)

#: Строка списка: «- », «* », «1. », «1) ». Номер не значим — важен порядок.
_BULLET = re.compile(r"^\s*(?:[-*•]|\d+[.)])\s+(.*\S)\s*$")

#: Сколько описаний берём максимум. Ограничение не косметическое: каждый
#: персонаж — это отдельная генерация референса, то есть деньги. Модель,
#: которой не поставить границу, охотно выдаёт пятнадцать «прохожих».
MAX_PEOPLE = 6
MAX_THINGS = 6

#: Промт по умолчанию. Живёт в коде, а не только файлом, потому что папки
#: `prompts/` на сервере может не быть вовсе — библиотека монтируется томом и
#: у заказчика неполна. Файл, если он есть, побеждает.
DEFAULT_PROMPT = """\
Ты разбираешь сценарий короткого ролика и выписываешь, кого и что придётся
нарисовать.

Верни РОВНО такой формат, без вступления и без пояснений:

ПЕРСОНАЖИ
- <краткое имя или роль> — <внешность: возраст, телосложение, одежда, приметы>
- ...

ПРЕДМЕТЫ
- <название> — <как выглядит>

Правила:
* Только те, кто реально появляется в кадре. Упомянутые вскользь — не в счёт.
* ОДНА СТРОКА — ОДИН персонаж. Группы разбивай поимённо: «четверо бойцов» это
  четыре строки, а не одна. По каждой строке будет нарисован отдельный
  референс, и общий портрет группы вместо четырёх лиц бесполезен.
* Не больше {max_people} персонажей и {max_things} предметов. Если больше —
  оставь самых важных.
* Описание — про внешний вид, а не про характер и не про сюжет. По нему будут
  рисовать картинку.
* Если персонажей или предметов нет — оставь раздел пустым, заголовок сохрани.
* Пиши по-русски.

СЦЕНАРИЙ:
{plan}

ЗАКАДРОВЫЙ ТЕКСТ:
{script}
"""


def build_prompt(plan: str, script: str, template: str | None = None) -> str:
    """Собрать запрос. `template` — содержимое файла промта, если он заведён."""
    body = (template or DEFAULT_PROMPT).strip()
    # `.format` по шаблону пользователя опасен: любая фигурная скобка в тексте
    # промта уронит шаг на KeyError. Меняем только известные метки.
    for key, value in (
        ("{max_people}", str(MAX_PEOPLE)),
        ("{max_things}", str(MAX_THINGS)),
        ("{plan}", (plan or "").strip() or "— не заполнен —"),
        ("{script}", (script or "").strip() or "— не заполнен —"),
    ):
        body = body.replace(key, value)
    # Промт пользователя может не содержать меток вовсе — тогда материал
    # дописывается в конец, иначе модель получила бы одни инструкции.
    if "{plan}" not in (template or DEFAULT_PROMPT) and (plan or script):
        body += f"\n\nСЦЕНАРИЙ:\n{(plan or '').strip()}\n\nЗАКАДРОВЫЙ ТЕКСТ:\n{(script or '').strip()}"
    return body


def parse_reply(reply: str) -> tuple[list[str], list[str]]:
    """Ответ модели → (персонажи, предметы).

    Разбор нарочно снисходительный. Модель ставит заголовки то с решётками, то
    жирным, нумерует списки по-разному и любит дописать «Вот что получилось».
    Требовать точный формат значит ронять шаг на пустом месте — а цена ошибки
    здесь мала: неудачную строку человек поправит в редакторе.
    """
    people: list[str] = []
    things: list[str] = []
    bucket: list[str] | None = None

    for raw in (reply or "").splitlines():
        line = raw.replace("**", "").replace("__", "").strip()
        if not line:
            continue
        if _HEAD_PEOPLE.match(line):
            bucket = people
            continue
        if _HEAD_THINGS.match(line):
            bucket = things
            continue
        if bucket is None:
            continue
        m = _BULLET.match(line)
        if not m:
            continue
        item = _clean(m.group(1))
        if item:
            bucket.append(item)

    return people[:MAX_PEOPLE], things[:MAX_THINGS]


def _clean(text: str) -> str:
    """Убрать обёртки, которые модель добавляет поверх формата."""
    out = text.strip().strip("«»\"'")
    # «Имя — описание» оставляем целиком: имя нужно, чтобы человек узнал, кого
    # правит. А вот пустое описание после тире бессмысленно.
    out = re.sub(r"\s*[—–-]\s*$", "", out)
    return out.strip()


async def extract_cast(project, gpt, *, template: str | None = None) -> tuple[list[str], list[str]]:
    """Спросить модель и вернуть (персонажи, предметы). Пустые списки — норма.

    Ошибку наружу не пускаем: вывод персонажей — удобство, а не обязанность
    шага. Упасть здесь значит остановить конвейер там, где раньше он просто шёл
    дальше с пустыми списками.
    """
    plan = (getattr(project, "general_plan", "") or "").strip()
    script = (getattr(project, "script_text", "") or "").strip()
    if not plan and not script:
        logger.info("[#{}] cast: ни плана, ни закадрового текста — выводить не из чего", project.id)
        return [], []

    prompt = build_prompt(plan, script, template)
    try:
        reply = await gpt.ask_fresh(prompt, project_id=project.id)
    except Exception as e:  # noqa: BLE001
        logger.warning("[#{}] cast: модель не ответила ({}) — списки остаются пустыми", project.id, e)
        return [], []

    people, things = parse_reply(reply)
    logger.info(
        "[#{}] cast: из плана выведено персонажей={} предметов={}",
        project.id,
        len(people),
        len(things),
    )
    return people, things
