"""Контракт хранилища: ключ, запись, чтение, ссылка на скачивание.

Сегодня медиа лежат в `data/videos/<slug>/`, а путь строится от
`project.data_dir`. Для одной машины это правильно и дёшево. В SaaS ломается
трижды: файл виден только тому узлу, который его записал; диск узла — предел
для всех арендаторов сразу; отдача идёт через приложение, то есть каждый
просмотр ролика занимает воркер (`docs/SAAS-PIVOT.md` §9.2).

Контракт зеркалит `llm-gateway/billing/src/storage/storage.service.ts` — тот
же продукт, та же касса, и расходиться им незачем. Оттуда же взяты три
решения, каждое из которых там уже оплачено практикой:

* **Изоляция префиксом ключа.** Арендатор физически не может назвать ключ вне
  своего префикса: путь санитизируется, а префикс приписывается кодом.
* **Выключено — значит выключено, а не сломано.** Нет ключей доступа →
  `enabled=False`, работает локальное хранилище, приложение поднимается. Режим
  владельца — это не «S3 ещё не настроили», а полноценный режим работы.
* **Жёсткая санитизация пути.** `..`, ведущие слэши, обратные слэши и
  управляющие символы вырезаются. Это poka-yoke: не «проверить, что вызывающий
  не подставил `..`», а «`..` не существует к моменту сборки ключа».

**Почему `presigned_url`, а не отдача через приложение.** Ролик — это десятки
мегабайт, и каждый просмотр, идущий через FastAPI, занимает воркер на всё
время скачивания. Подписанная ссылка отдаётся клиенту, а байты едут из
хранилища напрямую. Срок ссылки короткий: ссылка живёт дольше просмотра
ровно настолько, чтобы браузер успел докачать.
"""

from __future__ import annotations

import re
from pathlib import Path
from typing import Protocol, runtime_checkable

#: Управляющие символы в ключе — признак либо ошибки, либо попытки.
_CONTROL_RE = re.compile(r"[\0-\x1f]")

#: Верхний уровень ключей студии. Отдельный от `users/` биллинга намеренно:
#: там личный файловый менеджер пользователя, и складывать туда кадры значит
#: дать ему удалить их мимо проекта. Изоляция та же, соседство разное.
STUDIO_PREFIX = "studio"

#: Сколько живёт подписанная ссылка. Пятнадцати минут хватает докачать ролик
#: на плохом канале и мало для того, чтобы ссылка разошлась по чатам.
DEFAULT_URL_TTL_SEC = 900


class StorageError(RuntimeError):
    """Хранилище не смогло. Наружу уходит как 502/404, а не как трассировка."""


def safe_path(path: str) -> str:
    """Путь без выхода за пределы своего префикса.

    Возвращает нормализованный относительный путь. Пустой результат — ошибка:
    ключ без пути означал бы обращение к корню чужого префикса.
    """
    parts = [
        segment.strip()
        for segment in str(path or "").replace("\\", "/").split("/")
        if segment.strip() and segment.strip() not in (".", "..")
    ]
    clean = "/".join(parts)
    if not clean or _CONTROL_RE.search(clean):
        raise StorageError(f"недопустимый путь в хранилище: {path!r}")
    return clean


def tenant_key(tenant_id: str | None, path: str) -> str:
    """Полный ключ объекта. Префикс приписывается здесь, а не вызывающим.

    ``tenant_id=None`` — режим владельца: у него один префикс на всё, и это
    не дыра, а отсутствие арендаторов.
    """
    owner = tenant_id or "owner"
    return f"{STUDIO_PREFIX}/{owner}/{safe_path(path)}"


@runtime_checkable
class Storage(Protocol):
    """Что обязано уметь хранилище. Меньше не бывает, больше — по месту."""

    enabled: bool

    async def put_file(self, key: str, source: Path, *, content_type: str = "") -> str:
        """Положить локальный файл. Возвращает ключ."""

    async def get_bytes(self, key: str) -> bytes:
        """Прочитать объект целиком. Для мелочи: манифесты, субтитры."""

    async def exists(self, key: str) -> bool:
        """Есть ли объект. Дешевле, чем читать."""

    async def delete(self, key: str) -> None:
        """Удалить объект. Идемпотентно: нет — значит уже удалён."""

    def url(self, key: str, *, ttl_sec: int = DEFAULT_URL_TTL_SEC, download_name: str = "") -> str:
        """Ссылка, по которой клиент заберёт объект сам."""
