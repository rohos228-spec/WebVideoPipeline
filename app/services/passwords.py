"""Пароли: хеш, проверка, требования к стойкости.

До этого модуля пароль в проекте существовал ровно один — `WEB_AUTH_PASSWORD`,
открытым текстом в окружении, и сравнивался оператором `!=`. Это плохо по трём
причинам сразу, и каждая самостоятельна: значение видно всякому, кто читает
`.env` или список процессов; утечка окружения — это утечка доступа, а не хеша;
сравнение строк оператором `!=` заканчивается на первом несовпавшем символе, и
время ответа рассказывает, сколько символов угадано.

**Почему argon2id, а не bcrypt.** bcrypt молча обрезает пароль на 72 байтах —
парольная фраза из десяти русских слов в UTF-8 усечётся до пяти, и никто об
этом не узнает. argon2id длину не ограничивает и настраивается по памяти, а не
только по времени: подбор на GPU упирается в 64 МБ на попытку.

**Параметры.** Взяты по профилю OWASP «argon2id, 19 МиБ, t=2, p=1» и подняты
по памяти до 64 МиБ: студия — внутренний сервис, входов в сутки десятки, а не
десятки тысяч, и лишние 45 МиБ на проверку здесь ничего не стоят. Хеш несёт
параметры в себе, поэтому смена профиля не ломает старые: `needs_rehash`
скажет, что пора перехешировать, и это делается на успешном входе, когда
открытый пароль в руках.

**Требования к паролю.** Проверяются при заведении и смене, а не при входе:
пользователь с уже заведённым слабым паролем должен иметь возможность войти и
сменить его, а не оказаться заперт снаружи. Длина важнее состава — это позиция
NIST SP 800-63B, и она же причина, по которой здесь нет требования «одна
заглавная, одна цифра, один спецсимвол»: оно даёт `Password1!` и ничего больше.
"""

from __future__ import annotations

import unicodedata

from argon2 import PasswordHasher
from argon2.exceptions import InvalidHashError, VerificationError, VerifyMismatchError

#: Профиль argon2id. Память в кибибайтах.
_HASHER = PasswordHasher(
    time_cost=2,
    memory_cost=65536,  # 64 МиБ
    parallelism=1,
    hash_len=32,
    salt_len=16,
)

#: Минимальная длина. Двенадцать, а не восемь: восьмизначный пароль из
#: печатных ASCII перебирается на арендованной видеокарте за часы.
MIN_LENGTH = 12

#: Верхняя граница нужна не для стойкости, а против отказа в обслуживании:
#: argon2 честно посчитает хеш от мегабайтной строки и займёт этим ядро.
MAX_LENGTH = 1024

#: Пароли, которые не спасает никакая длина. Список короткий намеренно — это
#: не замена проверке по утечкам, а отсечка самых частых заглушек, которые
#: заводят «на время» и оставляют навсегда.
_BANNED = frozenset(
    {
        "password",
        "passw0rd",
        "qwertyuiop",
        "123456789012",
        "adminadmin12",
        "changeme1234",
        "letmein12345",
        "videopipeline",
        "studiostudio",
    }
)


class WeakPasswordError(ValueError):
    """Пароль не принят: он не удовлетворяет требованиям."""


def normalize(password: str) -> str:
    """NFKC перед хешированием — иначе один пароль даёт два разных хеша.

    «é» набирается одним кодом и двумя; визуально это один символ, для хеша —
    разные строки. Пользователь, сменивший раскладку или клавиатуру телефона,
    получил бы «неверный пароль» на верном пароле. Нормализуем и здесь, и при
    проверке — обязательно одинаково.
    """
    return unicodedata.normalize("NFKC", password or "")


def assert_strong(password: str) -> None:
    """Проверка при заведении и смене. Вход этой проверки не делает."""
    pwd = normalize(password)
    if len(pwd) < MIN_LENGTH:
        raise WeakPasswordError(f"пароль короче {MIN_LENGTH} символов: длина решает больше, чем состав")
    if len(pwd) > MAX_LENGTH:
        raise WeakPasswordError(f"пароль длиннее {MAX_LENGTH} символов")
    if pwd.strip() != pwd or not pwd.strip():
        raise WeakPasswordError("пароль не должен начинаться или заканчиваться пробелом")
    if pwd.lower() in _BANNED:
        raise WeakPasswordError("этот пароль встречается в списках подбора первым")
    if len(set(pwd)) < 5:
        # «aaaaaaaaaaaa» — двенадцать символов и один бит энтропии.
        raise WeakPasswordError("в пароле меньше пяти разных символов")


def hash_password(password: str) -> str:
    """Хеш argon2id. Соль внутри, параметры внутри, сравнивать нечего."""
    return _HASHER.hash(normalize(password))


def verify_password(password: str, stored_hash: str) -> bool:
    """Сходится ли пароль с хешем. Исключения наружу не выпускаются.

    Вызывающему нужен ответ «да/нет», а не разбор причины: «хеш битый» и
    «пароль неверный» для формы входа — одно и то же событие, а различать их
    в ответе значит рассказывать подбирающему, существует ли пользователь.
    """
    if not stored_hash:
        # Пользователя нет или у него нет пароля. Считаем хеш всё равно —
        # см. `dummy_verify`: без этого время ответа выдаёт список аккаунтов.
        return False
    try:
        return _HASHER.verify(stored_hash, normalize(password))
    except (VerifyMismatchError, VerificationError, InvalidHashError):
        return False
    except UnicodeEncodeError:
        # argon2-cffi кодирует хеш в ASCII и падает на любом другом байте.
        # В колонке лежит наш собственный вывод, поэтому такого быть не
        # должно — но «не должно» и «не бывает» это разные вещи: испорченная
        # строка в базе обязана давать отказ на форме входа, а не 500.
        return False


def needs_rehash(stored_hash: str) -> bool:
    """Хеш посчитан по устаревшему профилю — перехешировать на входе."""
    if not stored_hash:
        return False
    try:
        return _HASHER.check_needs_rehash(stored_hash)
    except (InvalidHashError, UnicodeEncodeError):
        return False


#: Хеш заведомо неизвестного пароля. Нужен, чтобы вход по НЕсуществующему
#: пользователю занимал столько же времени, сколько по существующему: иначе
#: форма входа превращается в справочник «есть такой аккаунт или нет».
_DUMMY_HASH = _HASHER.hash("* нет такого пользователя *")


def dummy_verify() -> None:
    """Сжечь столько же времени, сколько сожгла бы настоящая проверка."""
    try:
        _HASHER.verify(_DUMMY_HASH, "* заведомо не тот пароль *")
    except (VerifyMismatchError, VerificationError, InvalidHashError):
        return
