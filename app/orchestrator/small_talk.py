"""Короткие реплики без просьбы: приветствие, «спасибо», «ок», «помоги».

Отвечаются сразу, готовым текстом: задача не ставится, планировщик и модель
не зовутся, поэтому нет ни красного значка, ни ожидания. Срабатывает только
на всю реплику целиком: «помоги запустить проект 6» — уже просьба.
"""

from __future__ import annotations

import re

# Примеры, которые чат действительно выполняет (проверены живым прогоном
# студии): вопрос о проекте, сводка, траты, отчёт и запуск с карточкой.
HELP_EXAMPLES = (
    "что с проектом 4",
    "какие проекты требуют внимания",
    "сколько потратили сегодня",
    "отчёт по всем проектам в Excel",
    "запусти картинки в проекте 6",
)

HELP_TEXT = (
    "Я помогаю с проектами студии: рассказываю, что с ними происходит, и запускаю или меняю шаги. "
    "Напишите обычными словами, например:\n"
    + "\n".join(f"«{phrase}»" for phrase in HELP_EXAMPLES)
    + "\nВсё платное я сначала показываю карточкой и запускаю только после «Подтвердить»."
)
HELLO_TEXT = (
    "Привет. Напишите, что нужно, например «что с проектом 4» или «покажи проекты». "
    "Если не знаете, с чего начать, напишите «помоги»."
)
THANKS_TEXT = "Пожалуйста. Если что-то ещё нужно, напишите."
OK_TEXT = "Хорошо. Если что-то ещё нужно, напишите."
# «ок» при открытой карточке легко принять за согласие: ответ напоминает про кнопки.
CARD_WAITING_TEXT = (
    "Карточка ещё ждёт решения: нажмите на ней «Подтвердить» или «Отклонить». "
    "Без кнопки я ничего не запускаю."
)

