_FILLER = re.compile(r"(?<![а-яa-z])(?:пожалуйста|пж|плиз|please|мне|а|ну|эй|бот)(?![а-яa-z])")
_NOISE = re.compile(r"[^а-яa-z0-9 ]+")
_PUNCT = re.compile(r"[\s?!.,:;…\-]+")


def _norm(text: str) -> str:
    low = (text or "").lower().replace("ё", "е")
    return " ".join(_FILLER.sub(" ", _NOISE.sub(" ", low)).split())


_DECLINE = frozenset({"не", "ничего"})


def is_decline(text: str) -> bool:
    """«Спасибо, не надо», «спасибо, ничего»: при открытой карточке похоже на отказ от неё."""
    return any(word in _DECLINE for word in _norm(text).split())


def small_talk_reply(text: str) -> str | None:
    """Готовый ответ на реплику без просьбы. None — это просьба или вопрос по делу."""
    raw = (text or "").strip()
    if not raw:
        return None
    norm = _norm(raw)
    if not norm:
        # «?», «??», «...» — человек не знает, что спросить; «👍» и другие значки — согласие.
        if _NOISE.sub(" ", raw.lower()).strip():
            return None
        return HELP_TEXT if _PUNCT.fullmatch(raw) else OK_TEXT
    if norm in _HELP or (len(norm.split()) <= 6 and _HELP_RE.search(norm)):
        return HELP_TEXT
    if norm in _WHO:
        return WHO_TEXT
    if _TIME_RE.match(norm):
        return time_text()
    if norm in _NEVERMIND:
        return DECLINE_TEXT
    if _RUDE_RE.match(norm):
        return RUDE_TEXT
    if norm in _POLITE:
        return HELLO_TEXT if norm in _HELLO else THANKS_TEXT if norm in _THANKS else OK_TEXT
    # «ок спасибо», «привет спасибо»: только вежливые слова подряд.
    words = norm.split()
    if (
        len(words) <= 6
        and any(word in _THANKS for word in words)
        and all(word in _POLITE or word in _CLOSING for word in words)
    ):
        return THANKS_TEXT
    if _looks_like_noise(norm):
        return GIBBERISH_TEXT
    if len(words) <= 3 and all(word in _POLITE for word in words):
        if any(word in _THANKS for word in words):
            return THANKS_TEXT
        return HELLO_TEXT if any(word in _HELLO for word in words) else OK_TEXT
    return None
