def _upgrade_sqlite(bind: sa.engine.Connection) -> None:
    from app.orchestrator.db.migrations import JOURNAL_DDL, sqlite_statements, utc_now

    bind.exec_driver_sql(JOURNAL_DDL)
    applied = {row[0] for row in bind.exec_driver_sql("SELECT name FROM orch_schema_migrations")}

    def has_column(table: str, column: str) -> bool:
        inspector = sa.inspect(bind)
        if not inspector.has_table(table):
            return False
        return any(col["name"] == column for col in inspector.get_columns(table))

    for name in SQL_FILES:
        if name in applied:
            continue
        for statement in sqlite_statements(name, has_column):
            bind.exec_driver_sql(statement)
        bind.execute(
            sa.text("INSERT INTO orch_schema_migrations (name, applied_at) VALUES (:name, :at)"),
            {"name": name, "at": utc_now()},
        )
    for statement in _SQLITE_NOTICES:
        bind.exec_driver_sql(statement)


def upgrade() -> None:
    bind = op.get_bind()
    if bind.dialect.name == "sqlite":
        _upgrade_sqlite(bind)
        return
    for statement in _PG_UP:
        op.execute(sa.text(statement))


def downgrade() -> None:
    bind = op.get_bind()
    for table in _DROP_ORDER:
        op.execute(sa.text(f"DROP TABLE IF EXISTS {table}"))
    if bind.dialect.name == "sqlite":
        names = ", ".join(f"'{name}'" for name in SQL_FILES)
        if sa.inspect(bind).has_table("orch_schema_migrations"):
            bind.exec_driver_sql(f"DELETE FROM orch_schema_migrations WHERE name IN ({names})")
        return
    op.execute(sa.text("DROP FUNCTION IF EXISTS node_prompt_versions_immutable()"))
    op.execute(sa.text("DROP FUNCTION IF EXISTS node_defs_active_version_ref()"))
    op.execute(sa.text("DROP FUNCTION IF EXISTS notification_log_append_only()"))
