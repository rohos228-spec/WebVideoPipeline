"""Таблицы движка оркестратора: задачи, шаги, события и сообщения чата, ноды.

Revision ID: 0018
Revises: 0017
Create Date: 2026-10-22

Движок пришёл из линии, где эти таблицы создавал собственный раннер SQL
(``app/orchestrator/db/migrations/*.sql``) прямо в SQLite при первом
обращении. На Postgres так нельзя: схема сервера меняется только
миграциями, и до этой ревизии шина событий, очередь сообщений и задачи
супервизора на SaaS-базе падали бы на первой вставке.

* **SQLite** — выполняются те же SQL-файлы раннера, по одному оператору
  (триггеры внутри содержат ``;``), и каждый пишется в журнал
  ``orch_schema_migrations``. Схема получается байт в байт той, что строил
  раннер, а раннер после этой ревизии видит всё применённым. База, где
  раннер уже отработал, ничего нового не получает: файлы из журнала
  пропускаются, ``CREATE … IF NOT EXISTS`` не трогает существующее.
* **Postgres** — своя DDL того же смысла: ``BIGINT … IDENTITY`` вместо
  ``INTEGER PRIMARY KEY``, ``DOUBLE PRECISION`` вместо ``REAL``, проверка
  ключа ноды регулярным выражением вместо ``GLOB``, неизменяемость истории
  промптов — триггерами на plpgsql. Время остаётся ISO-строкой (так его
  пишет код), но с ``COLLATE "C"``: сравнение ``created_at < :cutoff`` при
  компакции событий обязано быть побайтовым, а не по правилам локали.

Сюда же — ``notification_log`` и ``chat_notices`` (уведомления в чат): их
тоже создавал сам код через ``executescript``.

**Арендатора у этих таблиц пока нет** (ни ``tenant_id``, ни RLS): движок
однопользовательский по происхождению. Это известный долг SaaS-режима,
закрывается отдельной ревизией вместе с привязкой сессий чата к арендатору.

downgrade служебный: удаляет таблицы вместе с данными (нужен тесту,
который проходит ревизии вниз).
"""

